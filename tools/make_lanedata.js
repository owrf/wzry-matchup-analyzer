// 英雄 → 主分路（按出现顺序，第一个为准）
const heroLane = {};
for (const [lane, names] of Object.entries(LANES)) {
  for (const n of names) {
    if (!heroLane[n]) heroLane[n] = [];
    if (!heroLane[n].includes(lane)) heroLane[n].push(lane);
  }
}

const out = "window.LANE_DATA = " + JSON.stringify({ lanes: LANES, heroLane }) + ";";
fs.writeFileSync(path.join(__dirname, "..", "英雄资料", "lanedata.js"), out, "utf8");

